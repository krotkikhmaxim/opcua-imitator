"""Manager-режим имитатора (WP-F): по экземпляру на пользователя.

Пакет подключается ТОЛЬКО в роли manager (ленивый импорт в конце
``app/main.py``): в single-режиме ни один его модуль не попадает в путь
импорта, и поведение процесса остаётся прежним байт-в-байт.

Состав:

- ``roles`` — единая точка разбора edge-заголовков и матрица прав
  (оператору запрещены изменяющие эндпоинты);
- ``instances`` — реестр дочерних экземпляров: порты, состояние,
  подъём/останов, чистка простоя, устойчивость слотов между рестартами;
- ``proxy`` — обратный прокси HTTP и ретрансляция WebSocket к дочернему
  процессу;
- ``routes`` — монтаж внутреннего API, шлюза ролей и диспетчеризации.
"""
